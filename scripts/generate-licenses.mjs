import { execSync } from 'child_process';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(__dirname, '..');

// ---------- 1. 收集前端直接依赖许可证 ----------
console.log('🔍 收集前端直接依赖许可证...');
let frontendLicenses = [];
try {
    const rootPackageJson = JSON.parse(
        fs.readFileSync(path.join(projectRoot, 'package.json'), 'utf8')
    );
    const dependencies = rootPackageJson.dependencies || {};

    for (const depName of Object.keys(dependencies)) {
        const depPackageJsonPath = path.join(projectRoot, 'node_modules', depName, 'package.json');
        if (fs.existsSync(depPackageJsonPath)) {
            const depPackageJson = JSON.parse(fs.readFileSync(depPackageJsonPath, 'utf8'));
            let license = depPackageJson.license;
            if (typeof license === 'string') {
                // 直接使用
            } else if (license && typeof license === 'object') {
                license = license.type || 'Unknown';
            } else if (Array.isArray(license)) {
                license = (license[0] && (license[0].type || license[0])) || 'Unknown';
            } else {
                license = 'Unknown';
            }
            frontendLicenses.push({
                name: depName,
                license: license || 'Unknown',
            });
        } else {
            console.warn(`⚠️ 未找到依赖 ${depName} 的 package.json，跳过`);
        }
    }
} catch (error) {
    console.warn('⚠️ 前端许可证收集失败:', error.message);
}

// ---------- 2. 收集 Rust 直接依赖许可证 ----------
console.log('🔍 收集 Rust 依赖许可证...');
let rustLicenses = [];
try {
    // 使用 cargo-license 获取直接依赖的许可证信息
    const cargoOutput = execSync(
        'cargo license --direct-deps-only --json',
        { cwd: path.join(projectRoot, 'src-tauri'), maxBuffer: 10 * 1024 * 1024 }
    ).toString();
    const cargoData = JSON.parse(cargoOutput);

    // 兼容 cargo-license 可能输出数组或对象
    const licenseList = Array.isArray(cargoData) ? cargoData : (cargoData.licenses || []);
    rustLicenses = licenseList.map(crate => ({
        name: crate.name,
        license: crate.license || crate.license_type || 'Unknown',
    }));
} catch (error) {
    console.warn('⚠️ Rust 许可证收集失败:', error.message);
}

// ---------- 去重：按 crate 名称保留第一个，并排序 ----------
const seen = new Set();
rustLicenses = rustLicenses.filter(dep => {
    const key = dep.name;
    if (seen.has(key)) return false;
    seen.add(key);
    return true;
});
rustLicenses.sort((a, b) => a.name.localeCompare(b.name));

// ---------- 手动许可证覆盖表 ----------
const licenseOverrides = {
    'umc_qmc': 'Apache-2.0 OR MIT',
    // 未来可添加其他需要修正的依赖
};

// 应用覆盖并确保覆盖的依赖存在
for (const [name, license] of Object.entries(licenseOverrides)) {
    const existing = rustLicenses.find(dep => dep.name === name);
    if (existing) {
        existing.license = license;           // 覆盖许可证
    } else {
        rustLicenses.push({ name, license }); // 如果不存在则新增
    }
}

// ---------- 格式化许可证 ----------
function formatLicense(license) {
    const trimmed = String(license).trim();
    if (trimmed.startsWith('(') && trimmed.endsWith(')')) {
        return `(${trimmed.slice(1, -1).trim()})`;
    }
    return `(${trimmed})`;
}

// ---------- 3. 生成 TypeScript 数据文件 ----------
console.log('📝 生成 src/data/licenses.ts ...');
const dataFileContent = `// Auto-generated by scripts/generate-licenses.mjs. Do not edit manually.

export interface ComponentInfo {
  name: string;
  license: string;
}

export const rustComponents: ComponentInfo[] = ${JSON.stringify(rustLicenses, null, 2)};

export const frontendComponents: ComponentInfo[] = ${JSON.stringify(frontendLicenses, null, 2)};
`;

const dataDir = path.join(projectRoot, 'src', 'data');
if (!fs.existsSync(dataDir)) fs.mkdirSync(dataDir, { recursive: true });
fs.writeFileSync(path.join(dataDir, 'licenses.ts'), dataFileContent);

// ---------- 4. 生成 NOTICE 文件 ----------
console.log('📝 生成 NOTICE ...');
let notice = `HotDownloader
Copyright 2026 lerd

This product includes software developed by independent third parties.
Each third-party component is governed by its own license, as indicated
below. For full license texts, please refer to the respective component's
official repository or documentation.

Third-party components:

Rust:
`;
for (const dep of rustLicenses) {
    notice += `  ${dep.name.padEnd(25)} ${formatLicense(dep.license)}\n`;
}

notice += `\nFrontend:\n`;
for (const dep of frontendLicenses) {
    notice += `  ${dep.name.padEnd(25)} ${formatLicense(dep.license)}\n`;
}

fs.writeFileSync(path.join(projectRoot, 'NOTICE'), notice);
console.log('✅ 许可证信息更新完成！');